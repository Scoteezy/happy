#!/usr/bin/env python3
"""Converts happy-ios's `extension Palette` in StemCellsTokens.swift into
layout's StemCellsPalette.kt, so the Stem Cells colours stay the same
literals as on iOS. Run from packages/happy-android:

    python3 tools/tokens/convert-stem-cells-palette.py
"""
import re
from pathlib import Path

SOURCE = Path("../happy-ios/Sources/HappyLayout/Tokens/StemCellsTokens.swift")
TARGET = Path("layout/src/main/kotlin/com/slopus/happy/layout/StemCellsPalette.kt")


def rgba(expr: str) -> str:
    def component(name: str) -> str:
        m = re.search(name + r":\s*([^,)]+(?:\([^)]*\))?[^,)]*)", expr)
        value = m.group(1).strip()
        return value if "." in value or "/" in value else value + ".0"
    return "RGBA({}, {}, {}, {})".format(*(component(n) for n in ("red", "green", "blue", "alpha")))


def main() -> None:
    text = SOURCE.read_text()
    body = text.split("extension Palette {", 1)[1].split("\n}\n", 1)[0]
    out = []
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("///"):
            out.append("    /**" + stripped[3:] + " */" if False else "    //" + stripped[3:])
            continue
        m = re.match(r"public static let (\w+) = ColorToken\((.*)\)$", stripped)
        if not m:
            if stripped:
                out.append("    // " + stripped)
            else:
                out.append("")
            continue
        name, args = m.groups()
        if args.startswith("light:"):
            light, dark = re.match(r"light:\s*(RGBA\(.*?\)),\s*dark:\s*(RGBA\(.*\))", args).groups()
            out.append(f"    val {name} = ColorToken({rgba(light)}, {rgba(dark)})")
        else:
            out.append(f"    val {name} = ColorToken({args})")
    TARGET.write_text(
        "package com.slopus.happy.layout\n\n"
        "// Generated by tools/tokens/convert-stem-cells-palette.py from happy-ios's\n"
        "// StemCellsTokens.swift (`extension Palette`). Do not edit by hand.\n\n"
        "object StemCellsPalette {\n" + "\n".join(out).rstrip() + "\n}\n"
    )


if __name__ == "__main__":
    main()
